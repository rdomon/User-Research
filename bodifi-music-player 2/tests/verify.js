// Real-browser verification script. Usage: npm i playwright && node tests/verify.js
const { chromium } = require('playwright');
const path=require('path');
const S=path.join(__dirname,'..','docs','screenshots')+path.sep;
(async()=>{
 const b=await chromium.launch(); const p=await b.newPage({viewport:{width:1280,height:800}});
 const errs=[]; p.on('pageerror',e=>errs.push('pageerror: '+e.message)); p.on('console',m=>{if(m.type()==='error')errs.push('console: '+m.text())});
 const res=[]; const t=(n,c)=>{res.push((c?'PASS':'FAIL')+'  '+n);};
 await p.goto('file://'+path.join(__dirname,'..','index.html'));
 const txt=async s=>(await p.textContent(s)).trim();
 t('Step 1 shows "Select instructor"', await txt('#setupTitle')==='Select instructor');
 await p.screenshot({path:S+'1-instructor.png'});
 await p.click('[data-pick="1"]');
 t('Pick Alex R. -> Music service, header shows Alex R.', await txt('#setupTitle')==='Music service' && await txt('#profileName')==='Alex R.');
 await p.screenshot({path:S+'2-service.png'});
 await p.click('[data-pick="0"]');
 t('Pick Spotify -> Class type', await txt('#setupTitle')==='Class type');
 await p.screenshot({path:S+'3-class.png'});
 await p.click('#backButton');
 t('Back -> Music service', await txt('#setupTitle')==='Music service');
 t('Unreached progress step is disabled', await p.isDisabled('[data-step="3"]'));
 await p.click('[data-pick="0"]');
 await p.click('[data-step="1"]');
 t('Progress step tap -> Music service', await txt('#setupTitle')==='Music service');
 await p.click('[data-pick="1"]');
 await p.click('[data-pick="1"]');
 t('Pick Dance Cardio -> Playlist', await txt('#setupTitle')==='Playlist');
 await p.screenshot({path:S+'4-playlist.png'});
 await p.click('#helpButton');
 t('Help opens', await p.isVisible('#helpOverlay'));
 await p.screenshot({path:S+'5-help.png'});
 await p.keyboard.press('Escape');
 t('Esc closes Help, stays on Playlist', !(await p.isVisible('#helpOverlay')) && await txt('#setupTitle')==='Playlist');
 await p.click('[data-pick="1"]');
 t('Pick playlist -> Now playing (paused, Neon Pulse)', await p.isVisible('#dashboard') && await txt('#trackTitle')==='Neon Pulse' && (await p.getAttribute('#playBtn','aria-label'))==='Play');
 t('Context line shows Apple Music / Dance Cardio (service re-picked at step 2)', (await txt('#ctxService'))==='Apple Music' && (await txt('#ctxClass'))==='Dance Cardio');
 t('Browse button count matches playlist (21 tracks)', (await txt('#browseBtn'))==='Browse all 21 tracks');
 await p.screenshot({path:S+'6-nowplaying.png'});
 await p.click('#playBtn');
 t('Play -> button becomes Pause', (await p.getAttribute('#playBtn','aria-label'))==='Pause');
 await p.waitForTimeout(2200);
 const el=await txt('#timeElapsed');
 t('Elapsed time advances while playing (got '+el+')', el!=='0:00');
 await p.click('#playBtn');
 t('Pause -> button becomes Play', (await p.getAttribute('#playBtn','aria-label'))==='Play');
 await p.click('[data-track="2"]');
 t('Tap track 3 -> After Hours, playing', await txt('#trackTitle')==='After Hours' && (await p.getAttribute('#playBtn','aria-label'))==='Pause');
 await p.click('#nextBtn'); t('Next -> Heartbeat City', await txt('#trackTitle')==='Heartbeat City');
 await p.click('#prevBtn'); t('Previous -> After Hours', await txt('#trackTitle')==='After Hours');
 await p.click('[data-track="4"]'); await p.click('#nextBtn');
 t('Next on last track wraps to first', await txt('#trackTitle')==='Neon Pulse');
 await p.fill('#songProgress','50');
 const e2=await txt('#timeElapsed');
 t('Seek to 50% -> elapsed ~1:42 (got '+e2+')', e2==='1:42');
 await p.fill('#volume','30');
 t('Volume slider updates label to 30%', await txt('#volumeLabel')==='30%');
 await p.click('#shuffleBtn');
 t('Shuffle toggles on (aria-pressed)', (await p.getAttribute('#shuffleBtn','aria-pressed'))==='true' && await p.isVisible('#toast'));
 const before=await txt('#trackTitle'); await p.click('#nextBtn');
 t('Shuffle Next picks a different track', (await txt('#trackTitle'))!==before);
 await p.click('#shuffleBtn');
 await p.click('#collapsePlaylist'); await p.waitForTimeout(400);
 t('Playlist collapses; Playlist button appears', await p.isVisible('#expandPlaylist'));
 await p.screenshot({path:S+'7-collapsed.png'});
 await p.click('#expandPlaylist'); await p.waitForTimeout(400);
 t('Playlist reopens', await p.isVisible('#trackList') && !(await p.isVisible('#expandPlaylist')));
 await p.click('#changePlaylist');
 t('Change -> Playlist selection', await txt('#setupTitle')==='Playlist');
 await p.click('[data-pick="2"]');
 t('Choose Sunday Reset -> Slow Morning, paused', await txt('#trackTitle')==='Slow Morning' && (await p.getAttribute('#playBtn','aria-label'))==='Play');
 await p.click('#profileButton');
 t('Header profile -> Select instructor', await txt('#setupTitle')==='Select instructor');
 // help from each setup step
 await p.click('[data-pick="0"]'); await p.click('#helpButton'); await p.click('#helpClose');
 t('Help works on step 2 and closes', !(await p.isVisible('#helpOverlay')));
 // mobile layout
 await p.setViewportSize({width:390,height:844}); await p.screenshot({path:S+'8-mobile.png'});
 const hs=await p.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1);
 t('Mobile 390px: no horizontal overflow', hs);
 t('No JS errors (excluding blocked Google Fonts)', errs.filter(e=>!/fonts\.g|ERR_|Failed to load resource/i.test(e)).length===0);
 console.log(res.join('\n')); console.log('\nRaw errors:',JSON.stringify(errs));
 await b.close();
})();
